public class MonthlyReport {

    private int winningDays;
    private int losingDays;
    private int totalAmount;
    private int luckiestDay;
    private int unluckiestDay;

    public int getWinningDays() {
        return winningDays;
    }

    public void setWinningDays(int winningDays) {
        this.winningDays = winningDays;
    }

    public int getLosingDays() {
        return losingDays;
    }

    public void setLosingDays(int losingDays) {
        this.losingDays = losingDays;
    }

    public int getTotalAmount() {
        return totalAmount;
    }

    public void setTotalAmount(int totalAmount) {
        this.totalAmount = totalAmount;
    }

    public int getLuckiestDay() {
        return luckiestDay;
    }

    public void setLuckiestDay(int luckiestDay) {
        this.luckiestDay = luckiestDay;
    }

    public int getUnluckiestDay() {
        return unluckiestDay;
    }

    public void setUnluckiestDay(int unluckiestDay) {
        this.unluckiestDay = unluckiestDay;
    }
}